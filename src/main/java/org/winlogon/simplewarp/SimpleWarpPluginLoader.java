package org.winlogon.simplewarp;

import io.papermc.paper.plugin.loader.PluginClasspathBuilder;
import io.papermc.paper.plugin.loader.PluginLoader;
import io.papermc.paper.plugin.loader.library.impl.MavenLibraryResolver;
import org.eclipse.aether.artifact.DefaultArtifact;
import org.eclipse.aether.graph.Dependency;
import org.eclipse.aether.repository.RemoteRepository;

import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.Properties;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Supplies the plugin's third-party dependencies by resolving them from Maven while the server loads the plugin.
 */
public final class SimpleWarpPluginLoader implements PluginLoader {

    /** Generated by the build from the version catalog; see the {@code generateLoaderLibraries} task. */
    private static final String DESCRIPTOR = "/loader-libraries.properties";
    private static final String DEPENDENCY_PREFIX = "loader.dependency.";
    private static final String REPOSITORY_PREFIX = "loader.repository.";
    private static final Pattern REPOSITORY_ID = Pattern.compile(Pattern.quote(REPOSITORY_PREFIX) + "(\\d+)\\.id");

    @Override
    public void classloader(PluginClasspathBuilder classpathBuilder) {
        final Properties descriptor = readDescriptor();
        final MavenLibraryResolver resolver = new MavenLibraryResolver();

        resolver.addRepository(new RemoteRepository.Builder(
                "central", "default", MavenLibraryResolver.MAVEN_CENTRAL_DEFAULT_MIRROR).build());

        for (final RemoteRepository repository : repositories(descriptor)) {
            resolver.addRepository(repository);
        }
        for (final String coordinate : dependencies(descriptor)) {
            resolver.addDependency(new Dependency(new DefaultArtifact(coordinate), "compile"));
        }

        classpathBuilder.addLibrary(resolver);
    }

    private static Properties readDescriptor() {
        final var descriptor = new Properties();
        try (var stream = SimpleWarpPluginLoader.class.getResourceAsStream(DESCRIPTOR)) {
            if (stream == null) {
                throw new IllegalStateException("Missing " + DESCRIPTOR + "; the plugin jar was not built correctly");
            }
            descriptor.load(stream);
        } catch (final IOException exception) {
            throw new IllegalStateException("Unable to read " + DESCRIPTOR, exception);
        }


        return descriptor;
    }

    /**
     * Reads the artifacts to resolve, in the order the build declared them.
     */
    private static List<String> dependencies(final Properties descriptor) {
        // Find keys matching "loader.dependency.<index>=<coordinate>", for example
        // "loader.dependency.0=org.example:loader-api:1.2.3".
        final TreeSet<Integer> indices = new TreeSet<>();
        for (final String key : descriptor.stringPropertyNames()) {
            if (key.startsWith(DEPENDENCY_PREFIX)) {
                // Parse the numeric index after "loader.dependency.", e.g. "0".
                indices.add(Integer.parseInt(key.substring(DEPENDENCY_PREFIX.length())));
            }
        }
    
        // Read each property's value in index order; the coordinate is kept as-is.
        final List<String> coordinates = new ArrayList<>();
        for (final Integer index : indices) {
            coordinates.add(descriptor.getProperty(DEPENDENCY_PREFIX + index));
        }
    
        // Return coordinates such as "org.example:loader-api:1.2.3".
        return coordinates;
    }

    /**
     * Reads the extra repositories the plugin needs beyond Maven Central. The descriptor describes each of them with
     * an {@code id}, a {@code type} and a {@code url}, so that the build stays the single source of truth for the
     * coordinates and the repositories alike.
     */
    private static List<RemoteRepository> repositories(final Properties descriptor) {
        final TreeSet<Integer> indices = new TreeSet<>();
        for (final String key : descriptor.stringPropertyNames()) {
            final Matcher matcher = REPOSITORY_ID.matcher(key);
            if (matcher.matches()) {
                indices.add(Integer.parseInt(matcher.group(1)));
            }
        }

        final List<RemoteRepository> repositories = new ArrayList<>();
        for (final Integer index : indices) {
            final String prefix = REPOSITORY_PREFIX + index + ".";
            repositories.add(new RemoteRepository.Builder(
                    descriptor.getProperty(prefix + "id"),
                    descriptor.getProperty(prefix + "type"),
                    descriptor.getProperty(prefix + "url")).build());
        }
        return repositories;
    }
}
